def test_staging_is_content_addressed():
    path = phase2b.staging_path(Path(r"C:\v\.staging"), "ab" + "c" * 62)
    assert path == Path(r"C:\v\.staging\ab\cc") / ("ab" + "c" * 62 + ".blob")


def test_stage_copies_verifies_and_moves_the_row(conn, config: Config, tmp_path: Path):
    import hashlib

    config.photos_root.mkdir(parents=True)
    payload = jpeg(card(900, 600))
    sha = hashlib.sha256(payload).hexdigest()
    origin = config.photos_root / "holiday.jpg"
    origin.write_bytes(payload)
    insert_file(conn, sha, ".jpg", len(payload), state="pending", relpath=None)

    result = phase2b.stage_gap(conn, config, [(sha, str(origin), len(payload))], readers=1)

    assert result["staged"] == 1 and result["mismatched"] == [] and result["failed"] == []
    staged = phase2b.staging_path(config.staging_root, sha)
    assert staged.read_bytes() == payload
    assert origin.read_bytes() == payload  # the photos root is never written
    state, relpath = conn.execute(
        "SELECT state, vault_relpath FROM file WHERE sha256 = ?", (sha,)
    ).fetchone()
    assert state == "staged"
    assert relpath == str(staged.relative_to(config.vault_root))
    # And it now decodes from the staged copy, not from the photos root.
    assert phase2b.worklist(conn, config)[0].source == str(staged)


def test_a_staged_copy_that_does_not_verify_is_refused(conn, config: Config):
    config.photos_root.mkdir(parents=True)
    origin = config.photos_root / "changed.jpg"
    origin.write_bytes(b"these are not the bytes the catalog recorded")
    sha = "9" * 64
    insert_file(conn, sha, ".jpg", 43, state="pending", relpath=None)

    result = phase2b.stage_gap(conn, config, [(sha, str(origin), 43)], readers=1)

    assert len(result["mismatched"]) == 1 and result["staged"] == 0
    assert not phase2b.staging_path(config.staging_root, sha).exists()
    assert not list(config.staging_root.rglob("*.part"))
    assert conn.execute(
        "SELECT state, vault_relpath FROM file WHERE sha256 = ?", (sha,)
    ).fetchone() == ("pending", None)


def test_the_gap_worklist_is_what_triage_keeps(conn):
    """Population 2 is sized by the rule set, never by a fixed figure -- the
    8,052-file gap it was once sized by was a census artefact."""
    conn.executescript(
        "INSERT INTO triage_ext (id, ext) VALUES (1, '.jpg'), (2, '.tmp');"
        "INSERT INTO triage_root (id, root) VALUES (1, 'sd');"
        "INSERT INTO triage_dir (id, path, path_key) VALUES (1, 'G:\\p', 'g:\\p');"
    )
    for index, (sha, ext_id, state) in enumerate(
        [("a" * 64, 1, "pending"), ("b" * 64, 2, "pending"), ("c" * 64, 1, "read")], start=1
    ):
        insert_file(conn, sha, ".jpg", 10, state=state, relpath="x" if state == "read" else None)
        conn.execute(
            "INSERT INTO triage_bucket (id, dir_id, root_id, ext_id, camera, paths, bytes)"
            " VALUES (?,1,1,?,0,1,10)", (index, ext_id)
        )
        conn.execute("INSERT INTO origin (id, path, root, ext, size, sha256, seen_at)"
                     " VALUES (?,?, 'sd', '.jpg', 10, ?, 'now')", (index, f"G:\\p\\{index}", sha))
        conn.execute("INSERT INTO triage_path VALUES (?,?)", (index, index))

    rules = [triage.Rule(0, triage.predicate("ext", "=", ".tmp"), "exclude")]
    kept = phase2b.gap_worklist(conn, rules)

    # `.tmp` is excluded by the rule; the `read` file already has its bytes.
    assert [row[0] for row in kept] == ["a" * 64]


def test_an_override_beats_the_rules_in_the_gap_worklist(conn):
    conn.executescript(
        "INSERT INTO triage_ext (id, ext) VALUES (1, '.jpg');"
        "INSERT INTO triage_root (id, root) VALUES (1, 'sd');"
        "INSERT INTO triage_dir (id, path, path_key) VALUES (1, 'G:\\p', 'g:\\p');"
        "INSERT INTO triage_bucket (id, dir_id, root_id, ext_id, camera, paths, bytes)"
        " VALUES (1,1,1,1,0,1,10);"
        "INSERT INTO origin (id, path, root, ext, size, sha256, seen_at)"
        " VALUES (1, 'G:\\p\\1', 'sd', '.jpg', 10, '" + "a" * 64 + "', 'now');"
        "INSERT INTO triage_path VALUES (1,1);"
        "INSERT INTO state.triage_override VALUES ('" + "a" * 64 + "', 'include', 'now');"
    )
    insert_file(conn, "a" * 64, ".jpg", 10, state="pending", relpath=None)

    rules = [triage.Rule(0, triage.predicate("ext", "=", ".jpg"), "exclude")]
    assert [row[0] for row in phase2b.gap_worklist(conn, rules)] == ["a" * 64]


