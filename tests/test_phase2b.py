def make_video(path: Path, *, size: str = "320x240", seconds: int = 2) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [FFMPEG, "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
         "-f", "lavfi", "-i", f"testsrc=duration={seconds}:size={size}:rate=10",
         "-pix_fmt", "yuv420p", str(path)],
        check=True, capture_output=True,
    )
    return path


def sink_for(conn, config: Config, long_edge: int | None = 4000) -> phase2b.Sink:
    """A `Sink` with the two metadata scalars stubbed, so a test that is about
    the pixels does not also need a manifest or an exiftool."""
    return phase2b.Sink(conn, config, {}, lambda item, result: (long_edge, None, False))


def insert_file(conn, sha256: str, ext: str, size: int, *, state: str, relpath: str | None):
    conn.execute(
        "INSERT INTO file (sha256, size, ext, kind, vault_relpath, state, feature_ver)"
        " VALUES (?,?,?,'image',?,?,'{}')",
        (sha256, size, ext, relpath, state),
    )


# --- the substrate and the tile ----------------------------------------------


def test_one_decode_produces_every_output():
    result = phase2b.decode_still(jpeg(card(3000, 2000)), phase2b.STILL_MAX_PIXELS)

    substrate = Image.open(io.BytesIO(result["substrate"]))
    tile = Image.open(io.BytesIO(result["tile"]))
    assert substrate.format == "WEBP" and tile.format == "WEBP"
    assert max(substrate.size) == phase2b.SUBSTRATE_EDGE
    assert max(tile.size) == phase2b.GRID_EDGE
    assert substrate.size == (result["deriv_w"], result["deriv_h"])
    # The native dimensions are the source's, not the substrate's.
    assert (result["native_w"], result["native_h"]) == (3000, 2000)
    assert isinstance(result["phash"], int) and isinstance(result["dhash"], int)
    assert isinstance(result["thumbhash"], bytes) and result["thumbhash"]
    assert result["quality"]["sharpness"] > 0
    assert result["quality"]["incomplete_decode"] == 0


def test_a_small_frame_is_never_upscaled():
    result = phase2b.decode_still(jpeg(card(200, 150)), phase2b.STILL_MAX_PIXELS)
    assert (result["deriv_w"], result["deriv_h"]) == (200, 150)
    assert Image.open(io.BytesIO(result["tile"])).size == (200, 150)


def test_exif_orientation_is_applied_before_anything_is_measured():
    """A JPEG carrying orientation 6 is stored turned and must come back upright.

    Measured by where the bright corner lands, not by the aspect: orientations 2,
    3 and 4 leave the aspect alone, so an aspect assertion would pass on a file
    that was never turned at all.
    """
    upright = card(900, 600)
    # Orientation 6 is undone by ROTATE_270, so the stored pixels are the
    # upright frame turned the other way.
    stored = upright.transpose(Image.ROTATE_90)
    exif = Image.Exif()
    exif[0x0112] = 6
    payload = jpeg(stored, exif=exif)

    result = phase2b.decode_still(payload, phase2b.STILL_MAX_PIXELS)
    substrate = Image.open(io.BytesIO(result["substrate"]))
    assert substrate.width > substrate.height
    assert brightest_quadrant(substrate) == brightest_quadrant(upright)


def test_a_truncated_still_is_decoded_and_flagged():
    payload = jpeg(card(900, 600))
    result = phase2b.decode_still(payload[: len(payload) // 2], phase2b.STILL_MAX_PIXELS)
    assert result["quality"]["incomplete_decode"] == 1
    assert result["substrate"]


def test_an_oversized_still_is_refused_before_its_pixels_load():
    with pytest.raises(ValueError, match="exceeds the"):
        phase2b._open_still(jpeg(card(900, 600)), 1000)


