def test_the_run_is_idempotent_at_row_granularity(conn, config: Config, tmp_path: Path):
    sha = "1" * 64
    source = tmp_path / "obj.blob"
    source.write_bytes(jpeg(card(900, 600)))
    insert_file(conn, sha, ".jpg", source.stat().st_size, state="read", relpath="obj.blob")
    config = dataclasses.replace(config, mediavault_root=tmp_path)

    items = phase2b.worklist(conn, config)
    assert len(items) == 1
    sink = sink_for(conn, config)
    phase2b.run_images(items, sink, readers=1, decoders=1)

    assert phase2b.worklist(conn, config) == []  # a second run has nothing to do


