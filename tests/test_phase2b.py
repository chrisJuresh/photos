@needs_exiftool
def test_exiftool_reads_through_one_stay_open_process(tmp_path: Path):
    """One process for the whole run, and it survives more than one file."""
    exif = Image.Exif()
    exif[0x0131] = "Adobe Photoshop 25.0"
    first = tmp_path / "a.jpg"
    first.write_bytes(jpeg(card(900, 600), exif=exif))
    second = tmp_path / "b.jpg"
    second.write_bytes(jpeg(card(200, 100)))

    with phase2b.ExifTool(EXIFTOOL) as tool:
        pid = tool.proc.pid
        long_edge, software, history = phase2b._metadata_from_exif(tool.read(str(first)))
        assert (long_edge, software, history) == (900, "Adobe Photoshop 25.0", False)
        assert phase2b._metadata_from_exif(tool.read(str(second)))[0] == 200
        assert tool.proc.pid == pid  # the same process, not a second spawn


